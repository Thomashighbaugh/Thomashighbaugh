// @ts-check

const fs = require('fs');
const path = require('path');

let satoriMod = null;
let sucraseMod = null;
let satoriInitialized = false;

async function ensureImports() {
  if (!satoriMod) {
    satoriMod = await import('satori');
  }
  if (!sucraseMod) {
    sucraseMod = await import('sucrase');
  }
}

/**
 * Minimal React-compatible element factory for JSX transpilation.
 */
function createElement(type, props, ...children) {
  const flat = children.flat().filter((c) => c != null && c !== false && c !== true);
  return {
    type,
    props: {
      ...(props ?? {}),
      children: flat.length === 0 ? undefined : flat.length === 1 ? flat[0] : flat,
    },
  };
}

/**
 * Parse a vice block's meta string.
 *
 * Supported keys:
 *   width=N height=N   — SVG dimensions (numbers, or `item.width` expressions)
 *   link="url"         — wrap the rendered image in an <a href>
 *   from=path.dotted   — render one SVG per item in the resolved context array
 *
 * @param {string} [meta]
 * @returns {{width: number|string, height: number|string, link?: string, from?: string}}
 */
function parseMeta(meta) {
  const defaults = { width: 800, height: 400 };
  if (!meta) return defaults;

  const pairs = [...meta.matchAll(/(\w+)=("[^"]*"|[^\s]+)/g)];
  for (const [, key, rawValue] of pairs) {
    const value = rawValue.startsWith('"') ? rawValue.slice(1, -1) : rawValue;
    if (key === 'width') defaults.width = /^\d+$/.test(value) ? parseInt(value, 10) : value;
    if (key === 'height') defaults.height = /^\d+$/.test(value) ? parseInt(value, 10) : value;
    if (key === 'link') defaults.link = value;
    if (key === 'from') defaults.from = value;
  }

  return defaults;
}

/**
 * Load font files from disk as Satori FontConfig entries.
 * Accepts .woff2, .woff, .ttf, .otf.
 * @param {string[]} fontPaths - absolute paths to font files
 * @returns {Promise<Array<{name: string, data: ArrayBuffer, weight: number, style: string}>>}
 */
async function loadFonts(fontPaths) {
  const fonts = [];
  for (const fontPath of fontPaths) {
    const ext = path.extname(fontPath).toLowerCase();
    if (!['.woff2', '.woff', '.ttf', '.otf'].includes(ext)) continue;

    const name = path
      .basename(fontPath, ext)
      .replace(/[-_](Regular|Bold|Italic|Light|Medium|SemiBold|ExtraBold|Black|\d+)/gi, '')
      .replace(/\s+/g, ' ');

    const buf = fs.readFileSync(fontPath);
    // Slice out the exact bytes: Buffer.buffer is a pooled ArrayBuffer that may
    // be larger than the file and may start at a non-zero byteOffset.
    const data = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
    const weight = /bold/i.test(fontPath) ? 700 : 400;

    fonts.push({ name, data, weight, style: 'normal' });
  }
  return fonts;
}

/**
 * Initialize Satori's WASM layout engine.
 *
 * The default build bundles the layout engine, so init() is a no-op there.
 * The standalone build (SATORI_STANDALONE=1) needs layout.wasm, which ships
 * at the package root — not inside dist/.
 */
async function initSatori() {
  if (satoriInitialized) return;
  const { init } = await import('satori');
  const wasmPath = path.resolve(path.dirname(require.resolve('satori')), '..', 'layout.wasm');
  await init({ wasmURL: wasmPath });
  satoriInitialized = true;
}

/**
 * Transpile a JSX string and render it to an SVG string via Satori.
 * @param {string} jsxString - JSX source (single root element)
 * @param {number} width - SVG width in px
 * @param {number} height - SVG height in px
 * @param {Array<{name: string, data: ArrayBuffer, weight?: number, style?: string}>} fonts
 * @param {Record<string, unknown>} [context] - variables injected into JSX (e.g. github, stats)
 * @returns {Promise<string>} SVG string
 */
async function renderJsx(jsxString, width, height, fonts = [], context = {}) {
  await ensureImports();
  await initSatori();

  const satori = satoriMod.default || satoriMod;
  const { transform } = sucraseMod;

  const wrapped = `return (${jsxString.trim()});`;
  const { code } = transform(wrapped, {
    transforms: ['jsx'],
    jsxRuntime: 'classic',
    production: true,
  });

  const argNames = ['React', ...Object.keys(context)];
  const argValues = [{ createElement }, ...Object.values(context)];
  const fn = new Function(...argNames, code);
  const element = fn(...argValues);

  if (!element || typeof element !== 'object' || !('type' in element)) {
    throw new Error(
      'JSX did not produce a valid element. Make sure your code returns a single root element.',
    );
  }

  const svg = await satori(element, {
    width,
    height,
    fonts,
  });

  return `<!-- Generated by vice https://github.com/Thomashighbaugh/Thomashighbaugh -->\n${svg}`;
}

module.exports = { renderJsx, createElement, parseMeta, loadFonts, initSatori };
